// Fallback logic for unsupported languages to reuse English template
const LANGUAGES = ['en', 'te', 'hi', 'ta', 'ml', 'kn'];
LANGUAGES.forEach(lang => {
  // If some key is missing in another language, fallback to English
  if (lang !== 'en') {
    Object.keys(LOCALES.en).forEach(key => {
      if (!LOCALES[lang][key]) {
        LOCALES[lang][key] = LOCALES[lang].btn_next ? LOCALES[lang][key] || LOCALES.en[key] : LOCALES.en[key];
      }
    });
  }
});

// Function to apply translation across the page
function applyTranslation() {
  const currentLang = localStorage.getItem('prajamitra_lang') || 'en';
  
  // Set language selector value
  const select = document.getElementById('language');
  if (select) select.value = currentLang;
  
  const translations = LOCALES[currentLang] || LOCALES.en;
  
  document.querySelectorAll('[data-translate]').forEach(element => {
    const key = element.getAttribute('data-translate');
    if (translations[key]) {
      if (element.tagName === 'INPUT' && (element.type === 'text' || element.type === 'search')) {
        element.placeholder = translations[key];
      } else {
        element.innerText = translations[key];
      }
    }
  });
}

// Function to set language and trigger update
function changeLanguage(langCode) {
  localStorage.setItem('prajamitra_lang', langCode);
  applyTranslation();
  
  // Custom event trigger if form needs to rebuild option labels
  const event = new CustomEvent('languageChanged', { detail: langCode });
  document.dispatchEvent(event);
}

// Initialize on script load
document.addEventListener('DOMContentLoaded', () => {
  const select = document.getElementById('language');
  if (select) {
    select.addEventListener('change', (e) => {
      changeLanguage(e.target.value);
    });
  }
  applyTranslation();
});
